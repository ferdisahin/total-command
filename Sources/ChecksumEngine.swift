import Foundation
import CryptoKit

enum ChecksumAlgorithm: String, CaseIterable, Equatable {
    case sha256 = "SHA-256"
    case md5 = "MD5"
    case sha1 = "SHA-1"
    case sha512 = "SHA-512"
    case crc32 = "CRC32 (SFV)"

    var fileExtension: String {
        switch self {
        case .sha256: return "sha256"
        case .md5: return "md5"
        case .sha1: return "sha1"
        case .sha512: return "sha512"
        case .crc32: return "sfv"
        }
    }
}

enum ChecksumStatus: Equatable {
    case ok
    case mismatch(expected: String, actual: String)
    case missing
    case error(String)

    var localizedTitle: String {
        switch self {
        case .ok: return L("Geçti (OK)")
        case .mismatch: return L("Hatalı (Uyuşmuyor)")
        case .missing: return L("Eksik (Bulunamadı)")
        case .error: return L("Hata")
        }
    }
}

struct ChecksumRecord: Equatable {
    let relativePath: String
    let expectedHash: String
    var actualHash: String?
    var status: ChecksumStatus
}

final class ChecksumEngine {
    static func calculateHash(url: URL, algorithm: ChecksumAlgorithm, control: JobState? = nil, progress: ((Int64, Int64) -> Void)? = nil) throws -> String {
        let fileSize = (try? url.resourceValues(forKeys: [.fileSizeKey]).fileSize).map(Int64.init) ?? 0
        let handle = try FileHandle(forReadingFrom: url)
        defer { try? handle.close() }

        let bufferSize = 1024 * 1024 // 1 MB buffer
        var bytesProcessed: Int64 = 0

        switch algorithm {
        case .crc32:
            let crc = CRC32()
            while true {
                if control?.cancelled == true { throw PanelError(message: L("İşlem iptal edildi.")) }
                guard let data = try? handle.read(upToCount: bufferSize), !data.isEmpty else { break }
                crc.update(data: data)
                bytesProcessed += Int64(data.count)
                progress?(bytesProcessed, fileSize)
            }
            return crc.hexString.lowercased()

        case .md5:
            var hasher = Insecure.MD5()
            while true {
                if control?.cancelled == true { throw PanelError(message: L("İşlem iptal edildi.")) }
                guard let data = try? handle.read(upToCount: bufferSize), !data.isEmpty else { break }
                hasher.update(data: data)
                bytesProcessed += Int64(data.count)
                progress?(bytesProcessed, fileSize)
            }
            return hasher.finalize().map { String(format: "%02x", $0) }.joined()

        case .sha1:
            var hasher = Insecure.SHA1()
            while true {
                if control?.cancelled == true { throw PanelError(message: L("İşlem iptal edildi.")) }
                guard let data = try? handle.read(upToCount: bufferSize), !data.isEmpty else { break }
                hasher.update(data: data)
                bytesProcessed += Int64(data.count)
                progress?(bytesProcessed, fileSize)
            }
            return hasher.finalize().map { String(format: "%02x", $0) }.joined()

        case .sha256:
            var hasher = SHA256()
            while true {
                if control?.cancelled == true { throw PanelError(message: L("İşlem iptal edildi.")) }
                guard let data = try? handle.read(upToCount: bufferSize), !data.isEmpty else { break }
                hasher.update(data: data)
                bytesProcessed += Int64(data.count)
                progress?(bytesProcessed, fileSize)
            }
            return hasher.finalize().map { String(format: "%02x", $0) }.joined()

        case .sha512:
            var hasher = SHA512()
            while true {
                if control?.cancelled == true { throw PanelError(message: L("İşlem iptal edildi.")) }
                guard let data = try? handle.read(upToCount: bufferSize), !data.isEmpty else { break }
                hasher.update(data: data)
                bytesProcessed += Int64(data.count)
                progress?(bytesProcessed, fileSize)
            }
            return hasher.finalize().map { String(format: "%02x", $0) }.joined()
        }
    }

    static func generateChecksumContent(files: [URL], baseDir: URL, algorithm: ChecksumAlgorithm, control: JobState? = nil, progress: ((Int, Int, String) -> Void)? = nil) throws -> String {
        var lines: [String] = []
        if algorithm == .crc32 {
            lines.append("; Generated by Total Command")
        }
        for (i, fileURL) in files.enumerated() {
            if control?.cancelled == true { throw PanelError(message: L("İşlem iptal edildi.")) }
            let relPath = fileURL.path.hasPrefix(baseDir.path) ? String(fileURL.path.dropFirst(baseDir.path.count)).trimmingCharacters(in: CharacterSet(charactersIn: "/")) : fileURL.lastPathComponent
            progress?(i, files.count, relPath)
            let hash = try calculateHash(url: fileURL, algorithm: algorithm, control: control)
            if algorithm == .crc32 {
                lines.append("\(relPath) \(hash.uppercased())")
            } else {
                lines.append("\(hash) *\(relPath)")
            }
        }
        return lines.joined(separator: "\n") + "\n"
    }

    static func parseChecksumFile(url: URL) throws -> (algorithm: ChecksumAlgorithm, records: [ChecksumRecord]) {
        let content = try String(contentsOf: url, encoding: .utf8)
        let ext = url.pathExtension.lowercased()
        var defaultAlgo: ChecksumAlgorithm?
        switch ext {
        case "sfv", "crc": defaultAlgo = .crc32
        case "md5": defaultAlgo = .md5
        case "sha1": defaultAlgo = .sha1
        case "sha256": defaultAlgo = .sha256
        case "sha512": defaultAlgo = .sha512
        default: defaultAlgo = nil
        }

        var detectedAlgo = defaultAlgo ?? .sha256
        var records: [ChecksumRecord] = []

        for rawLine in content.components(separatedBy: .newlines) {
            let line = rawLine.trimmingCharacters(in: .whitespaces)
            if line.isEmpty || line.hasPrefix(";") || line.hasPrefix("#") { continue }

            if line.contains(" = ") {
                let parts = line.components(separatedBy: " = ")
                if parts.count == 2 {
                    let hash = parts[1].trimmingCharacters(in: .whitespaces)
                    var fName = parts[0]
                    if let startParen = fName.firstIndex(of: "("), let endParen = fName.lastIndex(of: ")") {
                        fName = String(fName[fName.index(after: startParen)..<endParen])
                    }
                    records.append(ChecksumRecord(relativePath: fName.trimmingCharacters(in: .whitespaces), expectedHash: hash.lowercased(), actualHash: nil, status: .missing))
                    if defaultAlgo == nil { detectedAlgo = detectAlgoByHash(hash) }
                    continue
                }
            }

            let tokens = line.split(whereSeparator: { $0.isWhitespace })
            if tokens.count >= 2 {
                let firstToken = String(tokens[0])
                if isHexString(firstToken) && [8, 32, 40, 64, 128].contains(firstToken.count) {
                    let hash = firstToken.lowercased()
                    let pathPart = line.dropFirst(tokens[0].count).trimmingCharacters(in: .whitespaces)
                    let cleanPath = pathPart.hasPrefix("*") ? String(pathPart.dropFirst()) : pathPart
                    records.append(ChecksumRecord(relativePath: cleanPath, expectedHash: hash, actualHash: nil, status: .missing))
                    if defaultAlgo == nil { detectedAlgo = detectAlgoByHash(hash) }
                    continue
                }

                let lastToken = String(tokens.last!)
                if lastToken.count == 8 && isHexString(lastToken) {
                    let hash = lastToken.lowercased()
                    let pathPart = line.dropLast(lastToken.count).trimmingCharacters(in: .whitespaces)
                    records.append(ChecksumRecord(relativePath: pathPart, expectedHash: hash, actualHash: nil, status: .missing))
                    detectedAlgo = .crc32
                    continue
                }
            }
        }

        return (detectedAlgo, records)
    }

    static func verifyRecords(records: [ChecksumRecord], baseDir: URL, algorithm: ChecksumAlgorithm, control: JobState, progress: @escaping (Int, Int, ChecksumRecord) -> Void) throws -> [ChecksumRecord] {
        var results: [ChecksumRecord] = []
        for (i, rec) in records.enumerated() {
            if control.cancelled { throw PanelError(message: L("Doğrulama işlemi iptal edildi.")) }
            var updated = rec
            let fileURL = baseDir.appendingPathComponent(rec.relativePath)
            if !FileManager.default.fileExists(atPath: fileURL.path) {
                updated.status = .missing
            } else {
                do {
                    let actual = try calculateHash(url: fileURL, algorithm: algorithm, control: control)
                    updated.actualHash = actual
                    if actual.caseInsensitiveCompare(rec.expectedHash) == .orderedSame {
                        updated.status = .ok
                    } else {
                        updated.status = .mismatch(expected: rec.expectedHash, actual: actual)
                    }
                } catch {
                    updated.status = .error(error.localizedDescription)
                }
            }
            results.append(updated)
            progress(i + 1, records.count, updated)
        }
        return results
    }

    private static func detectAlgoByHash(_ hash: String) -> ChecksumAlgorithm {
        switch hash.count {
        case 8: return .crc32
        case 32: return .md5
        case 40: return .sha1
        case 128: return .sha512
        default: return .sha256
        }
    }

    private static func isHexString(_ s: String) -> Bool {
        !s.isEmpty && s.allSatisfy { $0.isHexDigit }
    }
}
